/** Пользовательская часть: только обезличенные данные, никаких имён. */
export function buildUserPrompt(snapshot: HintSnapshot): string {
  return `Данные команды на сейчас:

${JSON.stringify(snapshot, null, 2)}

Поля участника: rank — место в рейтинге, total_km — всего километров,
walks — число прогулок, streak_days — серия рабочих дней подряд,
days_since_last — сколько дней назад ходил последний раз (null — не ходил ни разу),
usual_speed — обычная скорость в км/ч.

Напиши ${HINTS_POOL_MAX} разных фраз: несколько про лидеров, несколько про тех,
кто давно не выходил, пару про команду целиком и 2–3 настоящих полезных совета
(tone: "tip", subject: null). Не повторяй одну и ту же шутку разными словами.`;
}
